// Bundles the ES modules in www/js into one classic script, www/js/app.bundle.js.
//
// Browsers refuse to load ES modules (and module workers) from file:// pages,
// so without this the site only works when served over http(s). The bundle
// works both ways: double-clicking index.html, or any web host.
//
// Usage: node scripts/build.mjs          write the bundle
//        node scripts/build.mjs --check  exit 1 if the bundle is out of date

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const jsDir = join(root, 'www', 'js');
export const BUNDLE_PATH = join(jsDir, 'app.bundle.js');

const WORKER_EXPR = "new Worker(new URL('./worker.js', import.meta.url), { type: 'module' })";
const INLINE_WORKER = "new Worker(URL.createObjectURL(new Blob([__WORKER_SOURCE__], { type: 'text/javascript' })))";

// Turns one module into a function that fills in its exports object.
function wrapModule(name, source) {
  let body = source.replace(
    /import\s*\{([^}]*)\}\s*from\s*'\.\/([\w.-]+)';/g,
    (_, names, dep) => `const {${names.replace(/\s+/g, ' ').trim()}} = __require('${dep}');`,
  );
  if (/\bimport\b[^(]/.test(body.replace(/import\.meta\.url/g, ''))) {
    throw new Error(`${name}: unsupported import syntax (only "import { a, b } from './x.js'" is bundled)`);
  }
  const exported = [];
  body = body.replace(/^export\s+(async\s+function|function|class|const|let)\s+([A-Za-z_$][\w$]*)/gm, (_, kind, id) => {
    exported.push(id);
    return `${kind} ${id}`;
  });
  if (/^export\b/m.test(body)) throw new Error(`${name}: unsupported export syntax`);
  return `__define('${name}', (__exports) => {\n${body}\nObject.assign(__exports, { ${exported.join(', ')} });\n});`;
}

function bundle(files, entry, prelude = '') {
  const modules = files.map((f) => wrapModule(f, readFileSync(join(jsDir, f), 'utf8'))).join('\n\n');
  return `(() => {
'use strict';
${prelude}
const __factories = {};
const __cache = {};
function __define(name, factory) { __factories[name] = factory; }
function __require(name) {
  if (!__cache[name]) { __cache[name] = {}; __factories[name](__cache[name]); }
  return __cache[name];
}

${modules}

__require('${entry}');
})();
`;
}

export function buildBundle() {
  const worker = bundle(['dsp.js', 'analysis.js', 'worker.js'], 'worker.js');
  const appFiles = ['dsp.js', 'charts.js', 'wav.js', 'live.js', 'file.js', 'app.js'];
  const fileSrc = readFileSync(join(jsDir, 'file.js'), 'utf8');
  if (!fileSrc.includes(WORKER_EXPR)) throw new Error('file.js: worker construction changed; update scripts/build.mjs');
  const app = bundle(appFiles, 'app.js', `const __WORKER_SOURCE__ = ${JSON.stringify(worker)};`)
    .replace(WORKER_EXPR, INLINE_WORKER);
  return `// GENERATED by scripts/build.mjs from the modules in this folder. Do not edit.\n${app}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = buildBundle();
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(BUNDLE_PATH, 'utf8'); } catch { /* missing */ }
    if (current !== out) {
      console.error('www/js/app.bundle.js is out of date. Run: npm run build');
      process.exit(1);
    }
    console.log('Bundle is up to date.');
  } else {
    writeFileSync(BUNDLE_PATH, out);
    console.log(`Wrote ${BUNDLE_PATH} (${(out.length / 1024).toFixed(0)} KB)`);
  }
}
